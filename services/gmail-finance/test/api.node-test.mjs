import test from 'node:test';
import assert from 'node:assert/strict';
import { setup } from './helpers.mjs';
import { createApp } from '../src/server.mjs';
import { samples } from './fixtures.mjs';
import { processPending } from '../src/pipeline.mjs';

test('API authentication, origin isolation, pagination, CSV and review',async t=>{
  const {config,store}=setup(t);const app=createApp(config,store);
  await new Promise(resolve=>app.server.listen(0,'127.0.0.1',resolve));config.port=app.server.address().port;
  t.after(()=>app.stop());
  const base=`http://127.0.0.1:${config.port}`;const headers={authorization:`Bearer ${config.apiKey}`,'content-type':'application/json'};
  assert.equal((await fetch(`${base}/health`)).status,200);
  assert.equal((await fetch(`${base}/api/ledger`)).status,401);
  assert.equal((await fetch(`${base}/api/ledger`,{headers:{...headers,origin:'https://evil.example'}})).status,403);
  const homepage=await fetch(base);assert.equal(homepage.status,200);assert.ok(homepage.headers.get('content-security-policy').includes("frame-ancestors 'none'"));
  assert.ok((await homepage.text()).includes('href="/favicon.svg"'));
  const iconRedirect=await fetch(`${base}/favicon.ico`,{redirect:'manual'});
  assert.equal(iconRedirect.status,302);assert.equal(iconRedirect.headers.get('location'),'/favicon.svg');
  const icon=await fetch(`${base}/favicon.svg`);
  assert.equal(icon.status,200);assert.equal(icon.headers.get('content-type'),'image/svg+xml');assert.ok((await icon.text()).includes('<svg'));
  for(const[id,raw]of samples)store.ingest(id,raw,{received:Date.parse('2026-09-26T17:00:00Z')});await processPending(store,config,100);
  const rows=await(await fetch(`${base}/api/ledger?limit=2`,{headers})).json();assert.equal(rows.items.length,2);assert.equal(rows.nextOffset,2);
  assert.ok(rows.items.every(row=>row.quality==='accepted'));assert.ok(rows.items.every(row=>!['obligation','statement'].includes(row.kind)));
  assert.equal((await fetch(`${base}/api/ledger?limit=-1`,{headers})).status,400);
  assert.equal((await fetch(`${base}/api/export.csv`,{headers})).headers.get('content-type'),'text/csv; charset=utf-8');
  const detail=await(await fetch(`${base}/api/messages/promo`,{headers})).json();assert.ok(detail.document.normalized.text.includes('Shop now'));
  const reviewed=await fetch(`${base}/api/messages/promo/review`,{method:'POST',headers,body:JSON.stringify({extraction:detail.document.extraction,note:'Verified promotion'})});assert.equal(reviewed.status,200);assert.equal((await reviewed.json()).disposition,'non_financial');
  assert.equal((await fetch(`${base}/api/messages/receipt/source`,{headers})).headers.get('content-type'),'message/rfc822');
  const sync=await fetch(`${base}/api/sync`,{method:'POST',headers,body:'{}'});assert.equal(sync.status,409);
});
